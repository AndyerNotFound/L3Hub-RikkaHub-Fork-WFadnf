/**
 * 组件的统一入口：按钮、卡片、顶栏都从这一层进来，调用点只认这里的签名，换实现只改这里。
 *
 * 内部实现：全部对齐上游 rikkahub，走 material3 原生组件（CardGroup 同一套体系），
 * 不再经过 ImageToolbox 引擎。公开签名与之前保持一致，调用方一行不用动。
 * fork 自有的观感参数保留：Switch 默认配色仍走 [glassSwitchColors]（玻璃特效）。
 */

